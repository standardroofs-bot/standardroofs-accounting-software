import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import {
  computeAttendanceBreakdownMap,
  computeGrossForCycle,
  computeHourlyOtAmount,
  computeMonthWorkingDaysInfo,
  getCycleDateRange,
} from "@/lib/payrollAttendanceSync";
import { getActiveTenantContext } from "@/lib/tenant";

function getPreviousCycle(month: string, halfPeriod: string): { month: string; halfPeriod: string } {
  const [yStr, mStr] = month.split("-");
  let y = Number(yStr);
  let m = Number(mStr);
  if (halfPeriod === "SECOND_HALF") return { month, halfPeriod: "FIRST_HALF" };
  m -= 1;
  if (m < 1) {
    m = 12;
    y -= 1;
  }
  return {
    month: `${y}-${String(m).padStart(2, "0")}`,
    halfPeriod: halfPeriod === "FIRST_HALF" ? "SECOND_HALF" : "FULL",
  };
}

async function autoGenerateDraftRun(cycleType: string, month: string, halfPeriod: string, companyId: string) {
  const empCategory =
    cycleType === "MONTHLY_OFFICE"
      ? "OFFICE_STAFF"
      : cycleType === "BI_MONTHLY_TAMIL"
      ? "TAMIL_LABOUR"
      : "HINDI_LABOUR";
  const itemCategory =
    cycleType === "MONTHLY_OFFICE"
      ? "OFFICE"
      : cycleType === "BI_MONTHLY_TAMIL"
      ? "TAMIL_LABOUR"
      : "HINDI_CREW";

  const { start, end, defaultWorkingDays } = getCycleDateRange(month, halfPeriod);
  const isOfficeCycle = cycleType === "MONTHLY_OFFICE";
  const monthInfo = isOfficeCycle ? await computeMonthWorkingDaysInfo(month, halfPeriod, companyId) : null;
  const effectiveWorkingDays = monthInfo?.scheduledWorkingDays || defaultWorkingDays;

  const employees = await prisma.employeeOrLabour.findMany({
    where: { active: true, status: "ACTIVE", category: empCategory, companyId },
    orderBy: { name: "asc" },
  });
  if (employees.length === 0) return null;

  const empIds = employees.map((e) => e.id);
  const advanceCategory = isOfficeCycle ? "Employee Advance" : "Labour Advance";
  const [attMap, perfList, advances] = await Promise.all([
    computeAttendanceBreakdownMap(empIds, month, halfPeriod, companyId),
    prisma.performanceReview.findMany({ where: { month, employeeId: { in: empIds } } }),
    prisma.cashBookEntry.findMany({
      where: {
        companyId,
        date: { gte: start, lte: new Date(end.getTime() + 86399999) },
        category: advanceCategory,
      },
    }),
  ]);

  const perfMap = new Map(perfList.map((p) => [p.employeeId, p]));

  const newItems = employees.map((emp) => {
    const att = attMap.get(emp.id);
    const hasRecords = Boolean(att && att.totalRecords > 0);
    const daysPresent = hasRecords
      ? isOfficeCycle
        ? att!.projectedPayableDays
        : att!.markedPayableSoFar
      : effectiveWorkingDays;
    const leaveDays = Math.max(0, Math.round((effectiveWorkingDays - daysPresent) * 100) / 100);
    const baseRate = isOfficeCycle
      ? Number(emp.monthlySalary || emp.baseWage || 0)
      : Number(emp.dailyWage || emp.baseWage || 0);
    const grossSalary = computeGrossForCycle(isOfficeCycle, baseRate, daysPresent, effectiveWorkingDays);

    const perf = perfMap.get(emp.id);
    const otAndIncentive = computeHourlyOtAmount(isOfficeCycle, baseRate, att?.otHours || 0, effectiveWorkingDays);
    const performanceIncentive = perf ? Number(perf.recommendedIncentive || 0) : 0;
    const isDriver = (emp.designation || "").toLowerCase().includes("driver");
    const vehicleAllowance = isDriver ? Number(emp.defaultVehicleAllowance || 0) : 0;
    const lastMonthBalance = 0;

    // Word-boundary CashBook advance matching
    const firstWord = emp.name.toLowerCase().trim().split(/[\s.]+/)[0];
    const wordRegex = firstWord.length >= 3 ? new RegExp(`\\b${firstWord.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "i") : null;
    const cashBookAdv = wordRegex
      ? advances.reduce((sum, a) => {
          const text = `${a.counterpartyName || ""} ${a.purpose || ""}`;
          if (!wordRegex.test(text)) return sum;
          const specific = text.match(new RegExp(`\\b${firstWord.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[^0-9]{0,6}(\\d+)`, "i"));
          if (specific) return sum + Number(specific[1]);
          return text.includes(",") ? sum : sum + Number(a.amount || 0);
        }, 0)
      : 0;
    const advanceDeduction = Math.round((att?.dailyAdvanceSum || 0) + cashBookAdv);

    const netSalary = Math.round(
      grossSalary + otAndIncentive + performanceIncentive + vehicleAllowance + lastMonthBalance - advanceDeduction
    );

    return {
      employeeId: emp.id,
      employeeName: emp.name,
      employeeCode: emp.employeeCode,
      category: itemCategory,
      company: emp.companyUnit || "STANDARD_ROOFS",
      totalWorkingDays: effectiveWorkingDays,
      daysPresent,
      leaveDays,
      baseRate,
      grossSalary,
      otAndIncentive,
      performanceIncentive,
      nightDutyAmount: 0,
      vehicleAllowance,
      lastMonthBalance,
      advanceDeduction,
      expenseBalanceDeduction: 0,
      netSalary,
      paidCash: 0,
      paidBankOrGpay: 0,
      paidGpay: 0,
      paymentChannel: "CASH",
      paymentStatus: "UNPAID",
      performanceScore: perf?.overallRating ?? null,
      carryForwardBalance: netSalary,
      isCleared: false,
      designation: emp.designation || emp.role || null,
      location: emp.location || "Erode",
      state: emp.state || "Tamil Nadu",
      mobileNo: emp.phone || null,
      aadhaarNo: emp.aadhaarNumber || null,
      bankName: emp.bankName || null,
      accountNo: emp.bankAccountNo || emp.bankAccountNumber || null,
    };
  });

  const totalGross = newItems.reduce((s, x) => s + x.grossSalary, 0);
  const totalDeductions = newItems.reduce((s, x) => s + x.advanceDeduction, 0);
  const totalNet = newItems.reduce((s, x) => s + x.netSalary, 0);

  return await prisma.payrollRun.create({
    data: {
      cycleType,
      month,
      halfPeriod,
      companyFilter: "ALL",
      companyId,
      status: "DRAFT",
      totalGross,
      totalDeductions,
      totalNet,
      paidCash: 0,
      paidBank: 0,
      items: { create: newItems },
    },
    include: { items: { orderBy: { employeeName: "asc" } } },
  });
}

export async function GET(req: NextRequest) {
  try {
    const tenant = await getActiveTenantContext();
    if (!tenant.userId) {
      return NextResponse.json({ success: false, error: "Authentication required." }, { status: 401 });
    }
    const { searchParams } = new URL(req.url);
    const runId = searchParams.get("runId");
    const cycleType = searchParams.get("cycleType") || "MONTHLY_OFFICE";
    const month = searchParams.get("month") || "2026-10";
    const halfPeriod = searchParams.get("halfPeriod") || (cycleType === "MONTHLY_OFFICE" ? "FULL" : "FIRST_HALF");
    const companyFilter = tenant.companyUnit;

    let run = runId
      ? await prisma.payrollRun.findFirst({
          where: { id: runId, companyId: tenant.companyId },
          include: { items: { orderBy: [{ employeeName: "asc" }] } },
        })
      : await prisma.payrollRun.findUnique({
          where: {
            cycleType_month_halfPeriod_companyFilter_companyId: {
              cycleType,
              month,
              halfPeriod,
              companyFilter: "ALL",
              companyId: tenant.companyId,
            },
          },
          include: {
            items: {
              orderBy: [{ employeeName: "asc" }],
            },
          },
        });

    // Auto-generate live draft for any current or future month (>= 2026-11) when empty
    if (!run && !runId && month >= "2026-11") {
      run = await autoGenerateDraftRun(cycleType, month, halfPeriod, tenant.companyId);
    }

    const availableRuns = await prisma.payrollRun.findMany({
      where: { cycleType, companyId: tenant.companyId },
      select: {
        id: true,
        month: true,
        halfPeriod: true,
        status: true,
        totalNet: true,
        paidCash: true,
        paidBank: true,
        _count: { select: { items: true } },
      },
      orderBy: [{ month: "desc" }, { halfPeriod: "desc" }],
    });

    if (!run) {
      return NextResponse.json({
        success: true,
        run: null,
        availableRuns,
        activeCompany: {
          id: tenant.companyId,
          code: tenant.companyCode,
          name: tenant.companyName,
          tagline: tenant.companyTagline,
        },
      });
    }

    const filteredItems = run.items;

    const empIds = Array.from(new Set(filteredItems.map((it) => it.employeeId).filter(Boolean)));
    const [attMap, perfList] = await Promise.all([
      computeAttendanceBreakdownMap(empIds, run.month, run.halfPeriod, tenant.companyId),
      prisma.performanceReview.findMany({
        where: { month: run.month, employeeId: { in: empIds } },
      }),
    ]);
    const perfMap = new Map(perfList.map((p) => [p.employeeId, p]));

    const enrichedItems = filteredItems.map((it) => {
      const att = attMap.get(it.employeeId);
      const isOfficeItem = it.category === "OFFICE";
      const hasAtt = Boolean(att && att.totalRecords > 0);
      const actualMarkedDays = isOfficeItem
        ? hasAtt
          ? Math.min(it.totalWorkingDays, att!.markedPayableSoFar)
          : it.daysPresent
        : it.daysPresent;
      const remainingWorkingDays =
        isOfficeItem && hasAtt
          ? Math.max(0, Math.min(att!.remainingScheduledDays, Math.max(0, it.totalWorkingDays - actualMarkedDays)))
          : 0;
      const earnedTillDate = isOfficeItem
        ? computeGrossForCycle(true, it.baseRate, actualMarkedDays, it.totalWorkingDays)
        : it.grossSalary;

      return {
        ...it,
        actualMarkedDays,
        remainingWorkingDays,
        earnedTillDate,
        attendanceSummary: att || {
          presentCount: 0,
          halfDayCount: 0,
          paidLeaveCount: 0,
          absentCount: 0,
          otHours: 0,
          payableDays: 0,
          markedPayableSoFar: actualMarkedDays,
          remainingScheduledDays: remainingWorkingDays,
          projectedPayableDays: it.daysPresent,
          scheduledWorkingDays: it.totalWorkingDays,
          dailyAdvanceSum: 0,
          totalRecords: 0,
        },
        performanceReview: perfMap.get(it.employeeId) || null,
      };
    });

    return NextResponse.json({
      success: true,
      run: {
        ...run,
        items: enrichedItems,
      },
      availableRuns,
      activeCompany: {
        id: tenant.companyId,
        code: tenant.companyCode,
        name: tenant.companyName,
        tagline: tenant.companyTagline,
      },
    });
  } catch (error: any) {
    console.error("[GET /api/payroll]", error);
    return NextResponse.json(
      { success: false, error: error.message || "Failed to load payroll" },
      { status: 500 }
    );
  }
}
